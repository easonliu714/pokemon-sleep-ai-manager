import assert from 'node:assert/strict';
import fs from 'node:fs';
import {normalizeWeeklyActivityBonusInput,projectWeeklyManualActivityBonus} from '../assets/js/weekly-manual-activity-bonuses.js';
const exact={source:'PLAYER_EXPLICIT_MANUAL_WEEKLY_OBSERVATION',values:{pot_multiplier:2,sleep_exp_multiplier:1.5,candy_use_exp_multiplier:3,observed_pot_capacity:null}};
const a=projectWeeklyManualActivityBonus({basePotSize:63,record:exact});
assert.equal(a.effective_pot_capacity,126);
assert.equal(a.base_pot_capacity,63);
assert.equal(a.pot_capacity_status,'MANUAL_MULTIPLIER_INTEGER_EXACT');
assert.equal(a.sleep_exp_multiplier,1.5);
assert.equal(a.candy_use_exp_multiplier,3);
assert.equal(a.sleep_exp_calculation_status,'DISPLAY_ONLY_UNVERIFIED');
assert.equal(a.candy_use_exp_calculation_status,'DISPLAY_ONLY_UNVERIFIED');
assert.equal(a.public_event_master_write,false);
assert.equal(a.account_base_pot_write,false);
const uncertain=projectWeeklyManualActivityBonus({basePotSize:63,record:{...exact,values:{pot_multiplier:1.5}}});
assert.equal(uncertain.pot_capacity_status,'REVIEW_FRACTIONAL_CAPACITY_ROUNDING');
assert.equal(uncertain.effective_pot_capacity,63,'no silent rounding into deterministic pot');
const observed=projectWeeklyManualActivityBonus({basePotSize:63,record:{...exact,values:{pot_multiplier:1.5,observed_pot_capacity:95}}});
assert.equal(observed.effective_pot_capacity,95);
assert.equal(observed.pot_capacity_status,'MANUAL_OBSERVED_EXACT');
assert.equal(projectWeeklyManualActivityBonus({basePotSize:63}).effective_pot_capacity,63);
assert.throws(()=>normalizeWeeklyActivityBonusInput({pot_multiplier:0.5}),/倍率/);
assert.throws(()=>normalizeWeeklyActivityBonusInput({observed_pot_capacity:94.5}),/整數/);
const weekly=fs.readFileSync('assets/js/effective-weekly-context.js','utf8');
const ui=fs.readFileSync('assets/js/weekly-manual-activity-bonuses-ui.js','utf8');
const sw=fs.readFileSync('service-worker.js','utf8');
const index=fs.readFileSync('index.html','utf8');
assert.match(weekly,/base_pot_size:playerContext\.pot_size/);
assert.match(weekly,/pot_size:manualBonus\.effective_pot_capacity/);
assert.match(weekly,/fieldSources\.pot_size='PLAYER_EXPLICIT_MANUAL_WEEKLY_ACTIVITY_BONUS'/);
assert.match(ui,/週期：/);
assert.match(ui,/candy_use_exp_multiplier/);
assert.match(ui,/sleep_exp_multiplier/);
assert.match(ui,/observed_pot_capacity/);
assert.match(sw,/weekly-manual-activity-bonuses\.js/);
assert.match(index,/weekly-manual-activity-bonuses-ui\.js/);
console.log(JSON.stringify({status:'PASS',gate:'WEEKLY_MANUAL_ACTIVITY_BONUSES',no_master_write:true,no_account_base_mutation:true,no_fractional_round_guess:true,week_scoped:true,display_only_experience:true}));
